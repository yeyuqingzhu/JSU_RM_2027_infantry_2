// =============================================================================
// tools/exiter.cpp —— tools/exiter.hpp 的实现（SIGINT → 退出标志）
// -----------------------------------------------------------------------------
// 【作用】定义进程级退出标志与“是否已安装信号处理器”的标志，并在 Exiter 构造时
//         用 std::signal 安装 SIGINT 处理器。
// 【来源】sp_vision_25 的 tools/exiter.cpp。
// 【依赖】<csignal>（std::signal、SIGINT）、<stdexcept>（std::runtime_error）。
// 【注意事项】
//   1) 线程安全：exit_ 为一个普通 bool，由信号处理器写、业务线程读。标准并不保证
//      跨线程/信号可见性（严格做法是 volatile sig_atomic_t 或 std::atomic<bool>），
//      源工程使用 bool，迁移时保持原样以免改变行为；实践中该标志会被很快观察到。
//   2) 单位：无。
//   3) 调用时机：Exiter 必须在程序启动早期构造；信号处理器只做“置位”这一件事，
//      满足异步信号安全（不调用非 async-signal-safe 函数）。
//   4) 只覆盖 SIGINT（Ctrl+C），不处理 SIGTERM/SIGQUIT；也不在退出时做任何清理。
// =============================================================================

#include "exiter.hpp"

#include <csignal>
#include <stdexcept>

namespace tools
{
// 全局退出标志：false = 继续运行，true = 已收到 SIGINT。
// 说明：写侧在信号处理器中（异步信号上下文），读侧在业务线程中；
//       源工程用普通 bool，迁移保持原样（严格做法见文件头注意事项）。
bool exit_ = false;
// 是否已经安装过 SIGINT 处理器：用于阻止创建第二个 Exiter（防止重复注册）。
bool exiter_inited_ = false;

// ----------------------------------------------------------------------------
// Exiter::Exiter() —— 安装 SIGINT 处理器
// ----------------------------------------------------------------------------
// 作用：检查全局唯一性并注册 SIGINT 处理器，处理器被调用时把 exit_ 置为 true。
// 参数：无。
// 返回：无。
// 边界：已存在实例时抛 std::runtime_error（不改变任何状态）；
//       处理器为无捕获 lambda，可隐式转换为函数指针，回调参数（信号编号）被忽略。
// 实现要点：std::signal(SIGINT, handler) 覆盖默认行为（默认行为是终止进程），
//           因此 Ctrl+C 之后进程不会立即退出，而是由业务线程轮询 exit_ 后自行收尾。
// ----------------------------------------------------------------------------
Exiter::Exiter()
{
  if (exiter_inited_) throw std::runtime_error("Multiple Exiter instances!");
  std::signal(SIGINT, [](int) { exit_ = true; });
  exiter_inited_ = true;
}

// ----------------------------------------------------------------------------
// bool Exiter::exit() const —— 查询退出标志
// ----------------------------------------------------------------------------
// 作用：返回全局退出标志的当前值。
// 参数：无。
// 返回：true 表示已收到 SIGINT。
// 边界：无；可在任意线程、任意频率调用（仅一次 bool 读取）。
// ----------------------------------------------------------------------------
bool Exiter::exit() const { return exit_; }

}  // namespace tools