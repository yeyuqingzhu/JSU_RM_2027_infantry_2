// =============================================================================
// tools/crc.hpp —— CRC8 / CRC16 校验（RoboMaster 下位机通信常用）
// -----------------------------------------------------------------------------
// 【作用】提供 8 位与 16 位 CRC 的“计算值”与“校验”两组接口，用于串口报文
//         （裁判系统、下位机、图传链路的帧尾校验）的完整性检查。
// 【来源】sp_vision_25 的 tools/crc.hpp。
// 【依赖】仅 C++17 标准库 <cstdint>，无第三方依赖，可在任意平台使用。
// 【注意事项】
//   1) 线程安全：纯函数、无静态可写状态，多线程并发调用安全。
//   2) 单位/长度：len 是“字节数”，不是元素个数；调用方必须保证 data 至少可读 len 字节。
//   3) 调用时机：既可在发送前计算校验值，也可在接收后校验整帧；
//      所有函数都不做缓冲区长度检查，越界读由调用方负责（见各函数边界说明）。
//   4) CRC 参数（初值、位序、多项式）与源工程完全一致，改动会导致与下位机协议不兼容。
// =============================================================================

#ifndef TOOLS__CRC_HPP
#define TOOLS__CRC_HPP

#include <cstdint>

namespace tools
{
// len不包括crc8
// 作用：计算 data 前 len 个字节的 CRC8 值。
// 参数：data —— 待校验数据首地址（不可为 nullptr，len > 0 时须可读 len 字节）；
//       len  —— 参与计算的字节数，不包含 CRC8 本身。
// 返回：CRC8 校验值（8 位）；len == 0 时返回初值 0xff。
// 边界：len == 0 合法（返回初值）；负长度不适用（形参为 uint16_t）。
// 备注：参数匹配“反射多项式 0x8C / 初值 0xff / 低位优先”，须与对端保持一致。
uint8_t get_crc8(const uint8_t * data, uint16_t len);

// len包括crc8
// 作用：校验一帧数据，其中最后一个字节是 CRC8。
// 参数：data —— 帧首地址；len —— 帧总字节数（含末尾 CRC8），必须 >= 1。
// 返回：true 表示 CRC 正确，false 表示数据被破坏。
// 边界：len == 0 时内部会以 len-1 回绕为 65535 并越界读取，调用方必须保证 len >= 1。
bool check_crc8(const uint8_t * data, uint16_t len);

// len不包括crc16
// 作用：计算 data 前 len 个字节的 CRC16 值。
// 参数：data —— 待校验数据首地址（不可为 nullptr，len > 0 时须可读 len 字节）；
//       len  —— 参与计算的字节数，不包含 CRC16 本身（32 位长度，支持超长帧）。
// 返回：CRC16 校验值；len == 0 时返回初值 0xffff。
// 边界：len == 0 合法；本函数不做空指针检查。
// 备注：参数匹配“反射多项式 0x8408（即 0x1021 的位反转）/ 初值 0xffff / 低位优先”，
//       即常见的 CRC-16/MCRF4XX；须与下位机协议保持一致。
uint16_t get_crc16(const uint8_t * data, uint32_t len);

// len包括crc16
// 作用：校验一帧数据，其中最后两个字节是 CRC16（小端：低字节在前、高字节在后）。
// 参数：data —— 帧首地址；len —— 帧总字节数（含末尾 2 字节 CRC16），必须 >= 2。
// 返回：true 表示 CRC 正确，false 表示数据被破坏。
// 边界：len < 2 时内部 len-2 会回绕成极大值并越界读取，调用方必须保证 len >= 2。
bool check_crc16(const uint8_t * data, uint32_t len);

}  // namespace tools

#endif  // TOOLS__CRC_HPP
