#ifndef TOOLS__TRAJECTORY_HPP
#define TOOLS__TRAJECTORY_HPP

// =============================================================================
// 文件：tools/trajectory.hpp
// -----------------------------------------------------------------------------
// 【本文件作用】
//   弹道解算结果与解算入口：给定子弹初速度 v0、目标水平距离 d、目标相对枪口的
//   竖直高度差 h，反解出枪口俯仰角 pitch 与弹丸飞行时间 fly_time。
//   采用**真空抛体模型（不考虑空气阻力）**，解析求解，无迭代、无状态。
//
// 【来源】
//   sp_vision_25 工程的 tools/trajectory.hpp（逐文件迁移）。
//   结构体名、成员名、构造函数签名与源工程完全一致，原有中文注释原样保留，
//   本次迁移只增加中文注释。
//
// 【依赖】
//   仅 C++ 标准库（实现文件用 <cmath>）；不依赖 Eigen / OpenCV 等任何第三方库。
//
// 【注意事项】
//   1. 单位：v0 为 m/s；d、h 为 m；pitch 为 rad（抬头为正，即目标高于枪口时为正）；
//      fly_time 为 s。角度单位是弧度而非度。
//   2. 模型误差：忽略空气阻力与弹速衰减，重力加速度取源工程标定值 9.7833 m/s²
//      （非标准 9.80665），因此解算结果只在配套标定的弹速下与实际弹道吻合。
//   3. 无解语义：判别式 < 0（距离超出该弹速的射程极限，或初速过小）时
//      unsolvable = true，此时 pitch / fly_time 没有物理意义。调用方**必须先判断
//      unsolvable**，再使用另外两个成员。
//   4. 双解选取：一元二次方程通常给出高低两条弹道，本实现取飞行时间更短的那条
//      （低伸平射弹道），与源工程一致。
//   5. 调用时机：解算是纯函数式的瞬时计算，可高频反复调用；但 v0 必须与实测弹速
//      一致，否则系统性偏高/偏低。
// =============================================================================

namespace tools
{
/** 弹道解算结果（真空抛体模型）。由构造函数一次性算好，之后只读。 */
struct Trajectory
{
  /**
   * 无解标志：true 表示当前 (v0, d, h) 下不存在可行的抛体弹道（判别式 < 0），
   * 此时 fly_time / pitch 不可使用。默认按"无解"这一保守值初始化。
   */
  bool unsolvable = true;

  /** 弹丸飞行时间，单位 s；取所选那条弹道对应的解。无解时无意义（已初始化为 0）。 */
  double fly_time = 0.0;

  /**
   * 枪口俯仰角，抬头为正，单位 rad；无解时无意义（已初始化为 0）。
   * 注：源文件中 unsolvable / fly_time / pitch 三个成员都没有默认初值，无解分支下
   *     读取 fly_time / pitch 会拿到未初始化的残留值（未定义行为），迁移时补上默认
   *     初值；这不影响任何已定义行为，详见迁移报告。
   */
  double pitch = 0.0;  // 抬头为正

  /**
   * 作用：解算弹道。根据 (v0, d, h) 求俯仰角与飞行时间，结果直接写入成员；
   *       无解时置 unsolvable = true 并立即返回。
   * 参数：
   *   - v0：子弹初速度大小，单位 m/s，必须 > 0。
   *   - d：目标水平距离，单位 m，正常使用时应 > 0（d = 0 时内部会退化，见 .cpp 说明）。
   *   - h：目标相对枪口的竖直高度差，单位 m，目标高于枪口为正。
   * 返回：无（构造函数）；结果从 unsolvable / pitch / fly_time 三个成员读取。
   * 边界条件：判别式 < 0 时 unsolvable = true，pitch / fly_time 保持默认值 0；
   *          v0 过小（或 d 过大）同样落入无解分支；v0 = 0 或 d = 0 会触发除零。
   */
  // 不考虑空气阻力
  // v0 子弹初速度大小，单位：m/s
  // d 目标水平距离，单位：m
  // h 目标竖直高度，单位：m
  Trajectory(const double v0, const double d, const double h);
};

}  // namespace tools

#endif  // TOOLS__TRAJECTORY_HPP
